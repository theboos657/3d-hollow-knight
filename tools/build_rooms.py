#!/usr/bin/env python3
"""Room builder: authors the world as code and writes assets/rooms/*.room.ron.

The RON files are what the game reads; this script is just a convenient way to
author them (rects and platforms instead of hand-typed ASCII). Run it from the
repo root:

    python3 tools/build_rooms.py            # write every room
    python3 tools/build_rooms.py --show B1  # print one room's map

Then check the result with `cargo run --release -p hk_tools --bin lint_rooms`.

Coordinates: x to the right, y UP, in tiles; (0, 0) is the bottom-left corner.
`top` arguments are the y of a surface (where feet stand), so a platform with
top=5 is one you stand on at y = 5.

Room shell: solid outer walls, a floor `floor` tiles thick (its top is y=floor)
and a one-tile ceiling. Doorways are cut into the shell with door_*/hatch_*.
"""

import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "assets", "rooms")

DOOR_H = 4  # doorways are this many tiles tall


class Room:
    def __init__(self, rid, name, theme, w, h, floor=2):
        self.id, self.name, self.theme = rid, name, theme
        self.w, self.h, self.floor = w, h, floor
        self.cells = [["." for _ in range(w)] for _ in range(h)]
        self.spawns, self.entries, self.exits = [], [], []
        self.benches, self.pickups = [], []
        self.fill(0, 0, w, floor, "#")
        self.fill(0, 0, 1, h, "#")
        self.fill(w - 1, 0, 1, h, "#")
        self.fill(0, h - 1, w, 1, "#")

    # ---- geometry ----
    def fill(self, x, y, w, h, c):
        for j in range(y, min(y + h, self.h)):
            for i in range(x, min(x + w, self.w)):
                if 0 <= i and 0 <= j:
                    self.cells[j][i] = c
        return self

    def air(self, x, y, w, h):
        return self.fill(x, y, w, h, ".")

    def block(self, x, w, top, y0=None):
        """Solid from y0 (default: the floor) up to `top`."""
        y0 = self.floor if y0 is None else y0
        return self.fill(x, y0, w, top - y0, "#")

    def slab(self, x, w, top, thick=1):
        """A solid platform, `thick` tiles thick, standing surface at `top`."""
        return self.fill(x, top - thick, w, thick, "#")

    def plat(self, x, w, top):
        """A one-way (jump-through) platform, surface at `top`."""
        return self.fill(x, top - 1, w, 1, "=")

    def spikes(self, x, w, y=None):
        y = self.floor if y is None else y
        return self.fill(x, y, w, 1, "^")

    # ---- doorways ----
    def door_left(self, y, to, entry):
        self.air(0, y, 1, DOOR_H)
        self.exits.append(((0.0, float(y), 1.5, float(DOOR_H)), to, entry))

    def door_right(self, y, to, entry):
        self.air(self.w - 1, y, 1, DOOR_H)
        self.exits.append(((self.w - 1.5, float(y), 1.5, float(DOOR_H)), to, entry))

    def hatch_floor(self, x, w, to, entry):
        """A hole in the floor; falling in leaves the room."""
        self.air(x, 0, w, self.floor)
        self.exits.append(((float(x), float(self.floor - 1), float(w), 1.0), to, entry))

    def hatch_ceiling(self, x, w, to, entry):
        """An opening in the ceiling; jumping into it leaves the room."""
        self.air(x, self.h - 1, w, 1)
        self.exits.append(((float(x), self.h - 2.5, float(w), 3.5), to, entry))

    # ---- things ----
    def entry(self, name, x, y, facing=1):
        self.entries.append((name, float(x), float(y), facing))

    def spawn(self, kind, x, y, persistent=False):
        self.spawns.append((kind, float(x), float(y), persistent))

    def bench(self, x, y):
        self.benches.append((float(x), float(y)))

    def pickup(self, ability, x, y):
        self.pickups.append((ability, float(x), float(y)))

    # ---- output ----
    def rows(self):
        return ["".join(r) for r in reversed(self.cells)]

    def ron(self):
        f = lambda v: f"{v:.1f}"
        o = [f'// {self.name} ({self.id}). Generated by tools/build_rooms.py; edit that, not this.']
        o.append("(")
        o.append(f'    id: "{self.id}",')
        o.append(f'    name: "{self.name}",')
        o.append(f"    theme: {self.theme},")
        o.append("    tiles: [")
        for r in self.rows():
            o.append(f'        "{r}",')
        o.append("    ],")
        o.append("    spawns: [")
        for kind, x, y, pers in self.spawns:
            extra = ", persistent: true" if pers else ""
            o.append(f"        (kind: {kind}, at: ({f(x)}, {f(y)}){extra}),")
        o.append("    ],")
        o.append("    entries: [")
        for name, x, y, facing in self.entries:
            o.append(f'        (name: "{name}", at: ({f(x)}, {f(y)}), facing: {facing}),')
        o.append("    ],")
        o.append("    exits: [")
        for (x, y, w, h), to, entry in self.exits:
            o.append(f'        (rect: ({f(x)}, {f(y)}, {f(w)}, {f(h)}), to: "{to}", entry: "{entry}"),')
        o.append("    ],")
        o.append("    benches: [")
        for x, y in self.benches:
            o.append(f"        (at: ({f(x)}, {f(y)})),")
        o.append("    ],")
        o.append("    pickups: [")
        for ab, x, y in self.pickups:
            o.append(f"        (ability: {ab}, at: ({f(x)}, {f(y)})),")
        o.append("    ],")
        o.append(")")
        return "\n".join(o) + "\n"


rooms = []


def new(*a, **k):
    r = Room(*a, **k)
    rooms.append(r)
    return r


