def main():
    args = sys.argv[1:]
    if args[:1] == ["--show"]:
        for r in rooms:
            if r.id == args[1]:
                print(f"{r.id} {r.name}  {r.w}x{r.h}")
                for j, row in enumerate(r.rows()):
                    print(f"{r.h - 1 - j:3d} {row}")
                return
        sys.exit(f"no room {args[1]}")
    os.makedirs(OUT, exist_ok=True)
    for r in rooms:
        path = os.path.join(OUT, f"{r.id}.room.ron")
        with open(path, "w") as fh:
            fh.write(r.ron())
    print(f"wrote {len(rooms)} rooms to {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
